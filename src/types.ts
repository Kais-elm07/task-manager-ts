/**
 * Domain types for the task manager.
 * These interfaces describe the shape of every object that flows through the app.
 */

/** Lifecycle of a task. A union type keeps the allowed values checked at compile time. */
export type TaskStatus = 'pending' | 'in-progress' | 'done';

export type TaskPriority = 'low' | 'medium' | 'high';

/** Runtime lists of the allowed values, used to validate untrusted input. */
export const TASK_STATUSES: readonly TaskStatus[] = ['pending', 'in-progress', 'done'];
export const TASK_PRIORITIES: readonly TaskPriority[] = ['low', 'medium', 'high'];

export interface User {
  readonly id: string;
  name: string;
  email: string;
}

export interface Task {
  readonly id: string;
  title: string;
  description?: string;
  status: TaskStatus;
  priority: TaskPriority;
  /** Id of the `User` this task is assigned to, if any. */
  assigneeId?: User['id'];
  readonly createdAt: Date;
  updatedAt: Date;
}

/** Data a caller provides to create a user; the id is generated by the service. */
export type CreateUserInput = Omit<User, 'id'>;

/** Data a caller provides to create a task; id, status and timestamps are generated. */
export interface CreateTaskInput {
  title: string;
  description?: string;
  priority?: TaskPriority;
  assigneeId?: User['id'];
}

/** Fields that may be changed on an existing task. */
export type UpdateTaskInput = Partial<Pick<Task, 'title' | 'description' | 'status' | 'priority'>>;

export interface TaskFilter {
  status?: TaskStatus;
  assigneeId?: User['id'];
}

/**
 * Outcome of an operation that can fail, without throwing.
 * A discriminated union: check `ok` and TypeScript narrows to `value` or `error`.
 */
export type Result<T, E extends Error = Error> =
  | { readonly ok: true; readonly value: T }
  | { readonly ok: false; readonly error: E };
